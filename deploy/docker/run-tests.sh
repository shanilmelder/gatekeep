#!/bin/sh
# Runs inside the tests container (deploy/compose.dev.yaml): the same steps CI used to
# run on the runner. Restore already ran, from lockfiles, when the image was built.
#
#   sh deploy/docker/run-tests.sh                   every stage, in order (local use)
#   sh deploy/docker/run-tests.sh checks            JS checks, .NET build, API contract, browser tests
#   sh deploy/docker/run-tests.sh architecture      .NET build, Architecture tests
#   sh deploy/docker/run-tests.sh isolation [k/n]   .NET and workspace builds, Isolation shard k of n (or all)
#
# CI runs the three stages as parallel jobs (.github/workflows/ci.yml), the Isolation
# tests as ISOLATION_SHARDS shards; together they run exactly what the first form runs.
set -eu

stage="${1:-all}"

# Testcontainers reaches its sibling containers through the Docker host. On Docker Desktop
# host.docker.internal can also resolve to an IPv6 address this container can't route to,
# so pin the override to the host's IPv4 address when there is one.
if [ "${TESTCONTAINERS_HOST_OVERRIDE:-}" = "host.docker.internal" ]; then
  ipv4="$(getent ahostsv4 host.docker.internal | awk 'NR == 1 { print $1 }')"
  if [ -n "$ipv4" ]; then
    export TESTCONTAINERS_HOST_OVERRIDE="$ipv4"
  fi
fi
echo "== Testcontainers host override: ${TESTCONTAINERS_HOST_OVERRIDE:-none}"

# The Isolation shards, balanced by measured run time. Shards 1 to ISOLATION_SHARDS - 1
# each name the namespaces under Gatekeep.Tests.Isolation they run; the last shard runs
# every test in none of them, so a namespace or root class added later lands there and is
# never skipped. The ci.yml matrix runs 1/N..N/N, N = ISOLATION_SHARDS.
ISOLATION_SHARDS=4
isolation_shard_namespaces() {
  case "$1" in
    1) echo "Protocol Hosting" ;;
    2) echo "Admins Audit Spikes" ;;
    3) echo "Applications Keys Apis Sessions" ;;
    *) echo "" ;;
  esac
}

js_checks() {
  echo "== pnpm audit"
  pnpm audit --audit-level critical

  echo "== design tokens: generator tests and drift check"
  pnpm --filter @gatekeep/design-tokens test
  pnpm --filter @gatekeep/design-tokens check

  echo "== ui: lint tests, bundled fonts, raw hex and hard-coded string lints"
  pnpm --filter @gatekeep/ui test
  pnpm --filter @gatekeep/ui check

  echo "== api-client: fetch wrapper tests"
  pnpm --filter @gatekeep/api-client test

  echo "== admin-dashboard: Session renewal tests"
  pnpm --filter @gatekeep/admin-dashboard test
}

dotnet_build() {
  echo "== build .NET solution"
  # The OpenAPI document is generated by this build, never left over from an earlier one.
  rm -rf src/Gatekeep.Host.Admin/obj/openapi
  dotnet build Gatekeep.slnx --no-restore
}

api_contract() {
  echo "== API contract: OpenAPI document and api-client drift check"
  sh deploy/docker/api-contract.sh
  sh deploy/docker/api-contract.sh --self-check
}

workspaces_build() {
  echo "== build workspaces"
  pnpm -r build
}

hosted_login_budget() {
  echo "== hosted-login: bundle budget check tests and the 150 kB gzip budget"
  pnpm --filter @gatekeep/hosted-login test
  pnpm --filter @gatekeep/hosted-login budget
}

browser_tests() {
  echo "== browser tests"
  pnpm --filter @gatekeep/browser-tests test
}

architecture_tests() {
  echo "== architecture tests"
  dotnet test tests/Architecture --no-build
}

# Isolation tests, all of them or one shard (with a VSTest filter). Detailed, so a fixture's
# cleanup failure prints its message and stack trace: at the default verbosity xUnit shows
# only "Test Assembly Cleanup Failure" and the exception type.
isolation_tests() {
  if [ "$#" -eq 0 ]; then
    echo "== isolation tests"
    dotnet test tests/Isolation --no-build --logger "console;verbosity=detailed"
    return
  fi

  # k/n: the workflow passes its matrix size, so a layout change here that the matrix
  # doesn't follow (a shard no job runs) fails every shard.
  shard="${1%/*}"
  if [ "${1#*/}" != "$ISOLATION_SHARDS" ]; then
    echo "isolation shard '$1': the layout has $ISOLATION_SHARDS shards; pass k/$ISOLATION_SHARDS." >&2
    exit 2
  fi
  expected="$(isolation_shard_check "$shard")"
  filter="$(isolation_shard_filter "$shard")"
  echo "== isolation tests: shard $shard of $ISOLATION_SHARDS, $expected tests"
  echo "== filter: $filter"

  log="$(mktemp)"
  status_file="$(mktemp)"
  # `set -e` would end the group at a failing `dotnet test` before the status is written,
  # so capture it with `||` (exempt from -e) and always write it.
  { code=0
    dotnet test tests/Isolation --no-build --filter "$filter" --logger "console;verbosity=detailed" || code=$?
    echo "$code" > "$status_file"; } 2>&1 | tee "$log"
  status="$(cat "$status_file")"
  if [ "$status" -ne 0 ]; then
    exit "$status"
  fi

  # The filter ran exactly the tests the shard's namespaces select from the discovered list.
  ran="$(sed -n 's/^Total tests: \([0-9]*\).*/\1/p' "$log" | tail -n 1)"
  if [ "$ran" != "$expected" ]; then
    echo "isolation shard $shard ran ${ran:-no} tests, but its namespaces select $expected." >&2
    exit 1
  fi
}

# The VSTest filter of a shard: its namespaces, or, for the last shard, none of the others'.
isolation_shard_filter() {
  prefix="FullyQualifiedName~Gatekeep.Tests.Isolation."
  if [ "$1" -lt "$ISOLATION_SHARDS" ]; then
    joined=""
    for ns in $(isolation_shard_namespaces "$1"); do
      joined="${joined:+$joined|}${prefix}${ns}."
    done
    echo "$joined"
  else
    joined=""
    i=1
    while [ "$i" -lt "$ISOLATION_SHARDS" ]; do
      for ns in $(isolation_shard_namespaces "$i"); do
        joined="${joined:+$joined&}FullyQualifiedName!~Gatekeep.Tests.Isolation.${ns}."
      done
      i=$((i + 1))
    done
    echo "$joined"
  fi
}

# Checks the shard layout against the discovered tests and prints this shard's test count:
# every named namespace holds tests (a renamed one would silently move to the last shard)
# and no test falls under two named namespaces. With the last shard the complement of the
# others, every test is then in exactly one shard.
isolation_shard_check() {
  shard="$1"
  case "$shard" in
    ''|*[!0-9]*) echo "isolation shard must be 1..$ISOLATION_SHARDS, not '$shard'." >&2; exit 2 ;;
  esac
  if [ "$shard" -lt 1 ] || [ "$shard" -gt "$ISOLATION_SHARDS" ]; then
    echo "isolation shard must be 1..$ISOLATION_SHARDS, not '$shard'." >&2
    exit 2
  fi

  list="$(mktemp)"
  dotnet test tests/Isolation --no-build --list-tests > "$list.raw"
  sed -n 's/^    \(Gatekeep\.Tests\.Isolation\.[^ (]*\).*/\1/p' "$list.raw" > "$list"
  if [ ! -s "$list" ]; then
    cat "$list.raw" >&2
    echo "no Isolation tests discovered." >&2
    exit 1
  fi

  layout=""
  i=1
  while [ "$i" -lt "$ISOLATION_SHARDS" ]; do
    for ns in $(isolation_shard_namespaces "$i"); do
      layout="$layout $i:$ns"
    done
    i=$((i + 1))
  done

  awk -v layout="$layout" -v shard="$shard" -v last="$ISOLATION_SHARDS" '
    BEGIN {
      n = split(layout, entries, " ")
      for (e = 1; e <= n; e++) {
        split(entries[e], pair, ":")
        owner["Gatekeep.Tests.Isolation." pair[2] "."] = pair[1]
      }
    }
    {
      hits = 0; in_shard = last
      for (p in owner) {
        if (index($0, p) == 1) { hits++; in_shard = owner[p]; seen[p]++ }
      }
      if (hits > 1) { print "test under two shard namespaces: " $0 > "/dev/stderr"; bad = 1 }
      if (in_shard == shard) count++
      total++
    }
    END {
      for (p in owner) {
        if (!(p in seen)) { print "shard " owner[p] " names " p " but no test is in it." > "/dev/stderr"; bad = 1 }
      }
      if (bad) exit 1
      print "discovered " total " Isolation tests; shard " shard " has " count + 0 > "/dev/stderr"
      print count + 0
    }' "$list"
}

case "$stage" in
  all)
    js_checks
    dotnet_build
    api_contract
    workspaces_build
    hosted_login_budget
    browser_tests
    architecture_tests
    isolation_tests
    ;;
  checks)
    js_checks
    dotnet_build
    api_contract
    workspaces_build
    hosted_login_budget
    browser_tests
    ;;
  architecture)
    dotnet_build
    architecture_tests
    ;;
  isolation)
    # The Hosted Login and admin bundles (pnpm -r build) are served by the Isolation hosts.
    dotnet_build
    workspaces_build
    if [ -n "${2:-}" ]; then
      isolation_tests "$2"
    else
      isolation_tests
    fi
    ;;
  *)
    echo "unknown stage '$stage': all, checks, architecture or isolation [k/$ISOLATION_SHARDS]." >&2
    exit 2
    ;;
esac
