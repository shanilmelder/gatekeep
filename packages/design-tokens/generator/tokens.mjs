// Drift check.

/**
 * Indexes the token lines of an output, keyed by the token's path: the CSS selector and
 * variable, the TypeScript key path, or the C# class path and constant.
 */
export function indexTokens(text) {
  const tokens = new Map();
  const stack = [];
  let selector = [];
  let pendingClass = null;
  for (const raw of text.replace(/\r\n/g, '\n').split('\n')) {
    const line = raw.trim();
    let match;
    if ((match = /^(--[\w-]+|color-scheme):/.exec(line))) {
      tokens.set(`${selector.join(' ')} ${match[1]}`, line);
    } else if ((match = /^"([^"]+)": \{$/.exec(line)) || (match = /^export const (\w+) = \{$/.exec(line))) {
      stack.push(match[1]);
    } else if ((match = /^"([^"]+)": (.+?),?$/.exec(line))) {
      tokens.set([...stack, match[1]].join('.'), line);
    } else if ((match = /^internal static class (\w+)$/.exec(line))) {
      pendingClass = match[1];
    } else if (line === '{' && pendingClass) {
      stack.push(pendingClass);
      pendingClass = null;
    } else if ((match = /^internal const string (\w+) = /.exec(line))) {
      tokens.set([...stack, match[1]].join('.'), line);
    } else if (/^\}(?: as const;)?,?$/.test(line)) {
      if (selector.length > 0) selector = [];
      else stack.pop();
    } else if (/[{,]$/.test(line) && !line.startsWith('"') && !line.startsWith('*') && !line.startsWith('/')) {
      // A CSS selector line: `:root,` and so on up to the line ending in `{`.
      selector.push(line.replace(/\s*\{$/, ''));
    }
  }
  return tokens;
}

/** Compares one committed output with what DESIGN.md generates. Returns the problems found. */
export function compareOutput(file, expected, actual) {
  if (actual === null) return [`${file}: missing. Run the generator.`];
  const normalize = (text) => text.replace(/\r\n/g, '\n');
  if (normalize(expected) === normalize(actual)) return [];

  const want = indexTokens(expected);
  const have = indexTokens(actual);
  const problems = [];
  for (const [token, line] of want) {
    if (!have.has(token)) problems.push(`${file}: token ${token} is missing (expected \`${line}\`).`);
    else if (have.get(token) !== line) problems.push(`${file}: token ${token} is \`${have.get(token)}\`, expected \`${line}\`.`);
  }
  for (const token of have.keys()) {
    if (!want.has(token)) problems.push(`${file}: token ${token} is not in DESIGN.md.`);
  }
  if (problems.length === 0) {
    const wantLines = normalize(expected).split('\n');
    const haveLines = normalize(actual).split('\n');
    const at = wantLines.findIndex((line, i) => line !== haveLines[i]);
    const lineNumber = (at === -1 ? wantLines.length : at) + 1;
    problems.push(`${file}: differs from the generated output at line ${lineNumber}, outside any token.`);
  }
  return problems;
}

/** Regenerates every output in memory from the repository at `root` and compares. */
export async function checkRepository(root) {
  const outputs = renderAll(await readFile(path.join(root, DESIGN_PATH), 'utf8'));
  const problems = [];
  for (const [file, expected] of Object.entries(outputs)) {
    let actual = null;
    try {
      actual = await readFile(path.join(root, file), 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    problems.push(...compareOutput(file, expected, actual));
  }
  return problems;
}
