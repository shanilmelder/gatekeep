// The design token generator (AD-22). DESIGN.md's frontmatter is the one token source:
// this module reads it and renders the CSS, TypeScript and C# outputs, and compares them
// with the committed files for the drift check. Every value that isn't plain CSS in the
// frontmatter (references, shorthand, the motion description) is mapped here, never by
// hand in an output.

import { readFile } from 'node:fs/promises';
import path from 'node:path';
import { parse } from 'yaml';

export const DESIGN_PATH = '_bmad-output/planning-artifacts/ux-designs/ux-gatekeep-2026-11-01/DESIGN.md';

export const OUTPUT_PATHS = {
  css: 'packages/design-tokens/css/tokens.css',
  ts: 'packages/design-tokens/src/tokens.generated.ts',
  cs: 'src/Modules/Tenancy/Core/Theme/DesignTokens.g.cs',
};

/** The Design System colours: each has a light value and a `-dark` value. */
export const SCHEME_COLORS = [
  'bg', 'sf', 'sf2', 'sf3', 'bd', 'bd2', 'tx', 'tx2', 'tx3',
  'ac', 'ac-sf', 'ac-tx', 'on-ac',
  'ok', 'ok-sf', 'warn', 'warn-sf', 'bad', 'bad-sf', 'info', 'info-sf',
  'code-bg', 'code-tx',
];

/** With `sh`, the 24 Design System tokens that change with the colour scheme. */
export const SCHEME_TOKENS = [...SCHEME_COLORS, 'sh'];

/** Family names the frontmatter uses, mapped to the stacks the outputs carry. */
export const FONT_STACKS = {
  Geist: '"Geist", ui-sans-serif, system-ui, sans-serif',
  'Geist Mono': '"Geist Mono", ui-monospace, SFMono-Regular, Menlo, monospace',
};

const GENERATED_NOTE =
  'Generated by packages/design-tokens/generator from the DESIGN.md frontmatter. Do not edit:\n' +
  'change DESIGN.md and run `pnpm --filter @gatekeep/design-tokens generate`.';

export class TokenError extends Error {
  constructor(message) {
    super(message);
    this.name = 'TokenError';
  }
}

const HEX = /^#(?:[0-9a-f]{3}|[0-9a-f]{6})$/i;
const PX = /^\d+(?:\.\d+)?px$/;
const LETTER_SPACING = /^-?\d*\.?\d+(?:em|px)$/;
const WEIGHT = /^[1-9]00$/;
const NAME = /^[a-z][a-z0-9-]*$/;
const SPACING_NAME = /^[a-z0-9][a-z0-9-]*$/;
const PROPERTY = /^[a-z][a-zA-Z0-9-]*$/;
const RGBA = /^rgba?\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}\s*(?:,\s*(?:0|1|0?\.\d+)\s*)?\)$/;
const SHADOW_LAYER = /^(?:-?\d*\.?\d+(?:px)?\s+){2,4}(rgba?\([^)]*\))$/;
const MOTION = /^(\d+)ms-(\d+)ms ([a-z][a-z-]*), (\d+)px rise and fade \((\w+)\)$/;
const SIZE_PAIR = /^(\d+(?:\.\d+)?)x(\d+(?:\.\d+)?)px$/;
// A component value is space-separated parts, each a whole reference, a length with a
// unit, zero, or one of these keywords. Any other word, such as a named colour, fails.
const REFERENCE_PART = /^'?\{([a-z]+)\.([a-z0-9-]+)\}'?$/;
const LENGTH_PART = /^(?:0|-?\d*\.?\d+(?:px|em|%|ms))$/;
const KEYWORDS = new Set(['none', 'transparent', 'currentColor', 'inherit', 'solid', 'dashed', 'dotted']);
/** Component properties whose YAML number is a count, emitted without a unit. */
const COUNT_PROPERTIES = new Set(['segments']);

/** Tokens the UI depends on: renaming one in DESIGN.md fails generation. */
export const REQUIRED = {
  typography: ['body'],
  components: { 'focus-ring': ['outlineWidth', 'outlineStyle', 'outlineColor', 'outlineOffset'] },
};

/** Returns the frontmatter of a Markdown document as text. */
export function frontmatterOf(markdown) {
  const text = markdown.replace(/^﻿/, '').replace(/\r\n/g, '\n');
  const match = /^---\n([\s\S]*?)\n---(?:\n|$)/.exec(text);
  if (!match) {
    throw new TokenError('DESIGN.md: no frontmatter between --- lines at the top of the file.');
  }
  return match[1];
}

/** Parses DESIGN.md and returns the token model, failing on the first bad key. */
export function parseDesign(markdown) {
  let front;
  try {
    front = parse(frontmatterOf(markdown));
  } catch (error) {
    if (error instanceof TokenError) throw error;
    throw new TokenError(`DESIGN.md: the frontmatter is not valid YAML: ${error.message}`);
  }
  if (!isObject(front)) {
    throw new TokenError('DESIGN.md: the frontmatter is not a YAML map.');
  }
  return buildModel(front);
}

function buildModel(front) {
  const colors = section(front, 'colors');
  const elevation = section(front, 'elevation');

  const schemes = { light: {}, dark: {} };
  for (const name of SCHEME_COLORS) {
    schemes.light[name] = hex(colors, name);
    schemes.dark[name] = hex(colors, `${name}-dark`);
  }
  schemes.light.sh = shadow(elevation, 'sh');
  schemes.dark.sh = shadow(elevation, 'sh-dark');

  // Every other colour is an extension, the same in both schemes.
  const invariant = {};
  for (const key of Object.keys(colors)) {
    if (SCHEME_COLORS.includes(key) || SCHEME_COLORS.some((n) => key === `${n}-dark`)) continue;
    checkName('colors', key);
    if (key.endsWith('-dark')) {
      throw new TokenError(`colors.${key}: a dark value with no light value. Extensions take one value.`);
    }
    invariant[key] = hex(colors, key);
  }

  const motion = elevation.motion;
  const motionMatch = typeof motion === 'string' ? MOTION.exec(motion) : null;
  if (!motionMatch) {
    throw new TokenError(
      `elevation.motion: ${describe(motion)} is not "<n>ms-<n>ms <easing>, <n>px rise and fade (<name>)".`);
  }
  if (Number(motionMatch[1]) > Number(motionMatch[2])) {
    throw new TokenError(`elevation.motion: the shorter duration ${motionMatch[1]}ms comes after the longer ${motionMatch[2]}ms.`);
  }
  for (const key of Object.keys(elevation)) {
    if (!['sh', 'sh-dark', 'scrim', 'motion'].includes(key)) {
      throw new TokenError(`elevation.${key}: unknown elevation token. The generator maps sh, sh-dark, scrim and motion.`);
    }
  }

  const model = {
    schemes,
    colors: invariant,
    typography: typography(section(front, 'typography')),
    rounded: lengths(section(front, 'rounded'), 'rounded'),
    spacing: lengths(section(front, 'spacing'), 'spacing'),
    elevation: {
      scrim: rgba(elevation, 'scrim'),
      motion: {
        durationMin: `${motionMatch[1]}ms`,
        durationMax: `${motionMatch[2]}ms`,
        easing: motionMatch[3],
        rise: `${motionMatch[4]}px`,
      },
    },
    components: {},
  };
  model.components = components(section(front, 'components'), model);

  for (const name of REQUIRED.typography) {
    if (!(name in model.typography)) throw new TokenError(`typography.${name}: missing. The UI depends on it.`);
  }
  for (const [name, props] of Object.entries(REQUIRED.components)) {
    for (const prop of props) {
      if (!(kebab(prop) in (model.components[name] ?? {}))) {
        throw new TokenError(`components.${name}.${prop}: missing. The UI depends on it.`);
      }
    }
  }

  // Both throw on a collision, so every rendered output is valid.
  sharedVariables(model);
  csPlan(model);
  return model;
}

function section(front, key) {
  const value = front[key];
  if (!isObject(value)) {
    throw new TokenError(`${key}: missing from the frontmatter, or not a map.`);
  }
  return value;
}

function hex(colors, key) {
  const value = colors[key];
  if (value === undefined) {
    throw new TokenError(`colors.${key}: missing. Every Design System colour needs a light and a -dark value.`);
  }
  if (typeof value !== 'string' || !HEX.test(value)) {
    throw new TokenError(`colors.${key}: ${describe(value)} is not a #rgb or #rrggbb colour.`);
  }
  return value.toLowerCase();
}

function shadow(elevation, key) {
  const value = elevation[key];
  if (value === undefined) {
    throw new TokenError(`elevation.${key}: missing.`);
  }
  const layers = typeof value === 'string' ? splitTopLevel(value) : [];
  const valid = layers.length > 0 && layers.every((layer) => {
    const match = SHADOW_LAYER.exec(layer);
    return match !== null && RGBA.test(match[1]);
  });
  if (!valid) {
    throw new TokenError(`elevation.${key}: ${describe(value)} is not a box-shadow of <x> <y> <blur> rgba() layers.`);
  }
  return layers.join(', ');
}

function rgba(elevation, key) {
  const value = elevation[key];
  if (typeof value !== 'string' || !RGBA.test(value)) {
    throw new TokenError(`elevation.${key}: ${describe(value)} is not an rgb() or rgba() colour.`);
  }
  return value;
}

function typography(styles) {
  const known = ['fontFamily', 'fontSize', 'fontWeight', 'lineHeight', 'letterSpacing'];
  const result = {};
  for (const [name, style] of Object.entries(styles)) {
    checkName('typography', name);
    const where = `typography.${name}`;
    if (!isObject(style)) throw new TokenError(`${where}: not a map.`);
    for (const key of Object.keys(style)) {
      if (!known.includes(key)) throw new TokenError(`${where}.${key}: unknown typography property.`);
    }
    const entry = {
      fontFamily: fontStack(style.fontFamily, `${where}.fontFamily`),
      fontSize: matching(style.fontSize, PX, `${where}.fontSize`, 'a px length'),
      fontWeight: matching(String(style.fontWeight ?? ''), WEIGHT, `${where}.fontWeight`, 'a weight from 100 to 900'),
      lineHeight: matching(style.lineHeight, PX, `${where}.lineHeight`, 'a px length'),
    };
    if (style.letterSpacing !== undefined) {
      entry.letterSpacing = matching(style.letterSpacing, LETTER_SPACING, `${where}.letterSpacing`, 'an em or px length');
    }
    result[name] = entry;
  }
  return result;
}

function fontStack(family, where) {
  const stack = typeof family === 'string' ? FONT_STACKS[family] : undefined;
  if (!stack) {
    throw new TokenError(`${where}: ${describe(family)} is not a bundled family (${Object.keys(FONT_STACKS).join(', ')}).`);
  }
  return stack;
}

function lengths(map, group) {
  const result = {};
  for (const [name, value] of Object.entries(map)) {
    checkName(group, name);
    result[name] = matching(value, PX, `${group}.${name}`, 'a px length');
  }
  return result;
}

function matching(value, pattern, where, expected) {
  if (typeof value !== 'string' || !pattern.test(value)) {
    throw new TokenError(`${where}: ${describe(value)} is not ${expected}.`);
  }
  return value;
}

function components(map, model) {
  const result = {};
  for (const [name, props] of Object.entries(map)) {
    checkName('components', name);
    if (!isObject(props)) throw new TokenError(`components.${name}: not a map.`);
    const entry = {};
    const set = (where, key, value) => {
      if (key in entry) throw new TokenError(`${where}: sets --gk-${name}-${key}, which another property of components.${name} already sets.`);
      entry[key] = value;
    };
    for (const [prop, value] of Object.entries(props)) {
      const where = `components.${name}.${prop}`;
      if (!PROPERTY.test(prop) || !NAME.test(kebab(prop))) {
        throw new TokenError(`${where}: property names are letters, digits and hyphens, starting with a lowercase letter.`);
      }
      const key = kebab(prop);
      if (typeof value === 'number') {
        if (!Number.isFinite(value)) throw new TokenError(`${where}: ${describe(value)} is not a finite number.`);
        if (value !== 0 && !COUNT_PROPERTIES.has(prop)) {
          throw new TokenError(`${where}: ${value} needs a unit (px, em, %, ms).`);
        }
        set(where, key, String(value));
        continue;
      }
      if (typeof value !== 'string') throw new TokenError(`${where}: ${describe(value)} is not a string or number.`);

      const size = SIZE_PAIR.exec(value);
      if (size) {
        set(where, `${key}-width`, `${size[1]}px`);
        set(where, `${key}-height`, `${size[2]}px`);
      } else if (prop === 'fontFamily') {
        set(where, key, fontStack(value, where));
      } else {
        set(where, key, componentValue(value, where, model));
      }
    }
    result[name] = entry;
  }
  return result;
}

/** Maps a component value part by part: whole references, lengths and keywords only. */
function componentValue(value, where, model) {
  const parts = value.trim().split(/\s+/);
  return parts.map((part) => {
    const reference = REFERENCE_PART.exec(part);
    if (reference) {
      const target = referenceVariable(reference[1], reference[2], model);
      if (!target) throw new TokenError(`${where}: unknown reference {${reference[1]}.${reference[2]}}.`);
      return `var(${target})`;
    }
    if (LENGTH_PART.test(part) || KEYWORDS.has(part)) return part;
    throw new TokenError(
      `${where}: ${describe(value)} has ${JSON.stringify(part)}, which is not a token reference, a length with a unit, or one of ${[...KEYWORDS].join(', ')}.`);
  }).join(' ');
}

function referenceVariable(group, name, model) {
  switch (group) {
    case 'colors':
      if (name === 'sh') return '--gk-elevation-sh';
      return name in model.schemes.light || name in model.colors ? `--gk-color-${name}` : null;
    case 'typography':
      return name in model.typography ? `--gk-font-${name}` : null;
    case 'rounded':
      return name in model.rounded ? `--gk-radius-${name}` : null;
    case 'spacing':
      return name in model.spacing ? `--gk-space-${name}` : null;
    case 'elevation':
      return name === 'sh' || name === 'scrim' ? `--gk-elevation-${name}` : null;
    default:
      return null;
  }
}

function checkName(group, name) {
  const pattern = group === 'spacing' ? SPACING_NAME : NAME;
  if (!pattern.test(name)) {
    throw new TokenError(group === 'spacing'
      ? `${group}.${name}: names are lowercase letters, digits and hyphens.`
      : `${group}.${name}: names are lowercase letters, digits and hyphens, starting with a letter.`);
  }
}

function splitTopLevel(value) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (const char of value) {
    if (char === '(') depth++;
    if (char === ')') depth--;
    if (char === ',' && depth === 0) {
      parts.push(current.trim());
      current = '';
    } else {
      current += char;
    }
  }
  parts.push(current.trim());
  return parts;
}

function kebab(name) {
  return name.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
}

function pascal(name) {
  return name.split('-').map((part) => part.charAt(0).toUpperCase() + part.slice(1)).join('');
}

function isObject(value) {
  return value !== null && typeof value === 'object' && !Array.isArray(value);
}

function describe(value) {
  return value === undefined ? 'a missing value' : JSON.stringify(value);
}

