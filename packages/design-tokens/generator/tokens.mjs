// Renderers. Each output is plain text with LF line endings, one token per line.

function typographyVariables(model) {
  const variables = [];
  for (const [name, style] of Object.entries(model.typography)) {
    const key = `typography.${name}`;
    variables.push([`--gk-font-${name}-family`, style.fontFamily, key]);
    variables.push([`--gk-font-${name}-size`, style.fontSize, key]);
    variables.push([`--gk-font-${name}-weight`, style.fontWeight, key]);
    variables.push([`--gk-font-${name}-line-height`, style.lineHeight, key]);
    if (style.letterSpacing) variables.push([`--gk-font-${name}-letter-spacing`, style.letterSpacing, key]);
    // The font shorthand can't carry letter-spacing: it's the -letter-spacing variable above.
    variables.push([`--gk-font-${name}`, `${style.fontWeight} ${style.fontSize}/${style.lineHeight} ${style.fontFamily}`, key]);
  }
  return variables;
}

function schemeVariables(values, scheme) {
  const suffix = scheme === 'dark' ? '-dark' : '';
  return Object.entries(values).map(([name, value]) =>
    name === 'sh'
      ? ['--gk-elevation-sh', value, `elevation.sh${suffix}`]
      : [`--gk-color-${name}`, value, `colors.${name}${suffix}`]);
}

/**
 * The variables every scope declares, as [name, value, source key]. Throws when two tokens
 * would emit the same variable, naming both keys.
 */
function sharedVariables(model) {
  const { motion } = model.elevation;
  const shared = [
    ...Object.entries(model.colors).map(([name, value]) => [`--gk-color-${name}`, value, `colors.${name}`]),
    ...typographyVariables(model),
    ...Object.entries(model.rounded).map(([name, value]) => [`--gk-radius-${name}`, value, `rounded.${name}`]),
    ...Object.entries(model.spacing).map(([name, value]) => [`--gk-space-${name}`, value, `spacing.${name}`]),
    ['--gk-elevation-scrim', model.elevation.scrim, 'elevation.scrim'],
    ['--gk-motion-duration-min', motion.durationMin, 'elevation.motion'],
    ['--gk-motion-duration-max', motion.durationMax, 'elevation.motion'],
    ['--gk-motion-easing', motion.easing, 'elevation.motion'],
    ['--gk-motion-rise', motion.rise, 'elevation.motion'],
    ...Object.entries(model.components).flatMap(([name, props]) =>
      Object.entries(props).map(([prop, value]) => [`--gk-${name}-${prop}`, value, `components.${name}.${prop}`])),
  ];
  const seen = new Map(schemeVariables(model.schemes.light, 'light').map(([name, , key]) => [name, key]));
  for (const [name, , key] of shared) {
    if (seen.has(name) && seen.get(name) !== key) {
      throw new TokenError(`${key}: emits ${name}, which ${seen.get(name)} already emits.`);
    }
    seen.set(name, key);
  }
  return shared;
}

export function renderCss(model) {
  const block = (selector, variables) =>
    `${selector} {\n${variables.map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;
  return [
    `/*\n * ${GENERATED_NOTE.replace(/\n/g, '\n * ')}\n *\n` +
      ' * :root carries the default (light) theme. [data-gk-theme] starts a themed subtree, such as a\n' +
      ' * preview, and [data-gk-scheme="dark"] switches that subtree to the dark values. Component\n' +
      ' * variables are declared on every scope, so their references resolve against its scheme.\n */\n',
    block(':root,\n[data-gk-theme],\n[data-gk-scheme="light"]',
      [['color-scheme', 'light'], ...schemeVariables(model.schemes.light, 'light')]),
    block('[data-gk-scheme="dark"]', [['color-scheme', 'dark'], ...schemeVariables(model.schemes.dark, 'dark')]),
    block(':root,\n[data-gk-theme],\n[data-gk-scheme]', sharedVariables(model)),
  ].join('\n');
}

export function renderTs(model) {
  const body = JSON.stringify(model, null, 2);
  return (
    `// ${GENERATED_NOTE.replace(/\n/g, '\n// ')}\n\n` +
    `export const tokens = ${body} as const;\n\n` +
    'export type Tokens = typeof tokens;\n' +
    "export type Scheme = keyof Tokens['schemes'];\n" +
    "export type SchemeToken = keyof Tokens['schemes']['light'];\n"
  );
}

const CS_IDENTIFIER = /^[A-Z][A-Za-z0-9]*$/;

/**
 * The C# classes and constants as a tree. Throws, naming the key, on an identifier that
 * isn't valid, that two names map to, or that matches its enclosing class.
 */
function csPlan(model) {
  const constant = (name, value, key) => ({ name, value, key });
  const node = (name, key, summary, members) => {
    const seen = new Map();
    for (const member of members) {
      if (!CS_IDENTIFIER.test(member.name)) {
        throw new TokenError(`${member.key}: maps to ${JSON.stringify(member.name)}, which is not a C# identifier.`);
      }
      if (member.name === name) {
        throw new TokenError(`${member.key}: maps to ${member.name}, the name of its enclosing C# class.`);
      }
      if (seen.has(member.name)) {
        throw new TokenError(`${member.key}: maps to the C# name ${member.name}, as ${seen.get(member.name)} does.`);
      }
      seen.set(member.name, member.key);
    }
    return { name, key, summary, members };
  };
  const entries = (map, group, naming = pascal) =>
    Object.entries(map).map(([name, value]) => constant(naming(name), value, `${group}.${name}`));

  return node('DesignTokens', 'DesignTokens', null, [
    ...['light', 'dark'].map((scheme) =>
      node(pascal(scheme), scheme, `The ${SCHEME_TOKENS.length} Design System tokens in the ${scheme} scheme.`,
        schemeVariables(model.schemes[scheme], scheme).map(([, value, key], index) =>
          constant(pascal(SCHEME_TOKENS[index]), value, key)))),
    node('Colors', 'colors', 'Extension colours: one value in both schemes.', entries(model.colors, 'colors')),
    node('Typography', 'typography', 'The type scale and its extensions.',
      Object.entries(model.typography).map(([name, style]) =>
        node(pascal(name), `typography.${name}`, null, Object.entries(style).map(([prop, value]) =>
          constant(pascal(kebab(prop)), value, `typography.${name}.${prop}`))))),
    node('Rounded', 'rounded', 'Corner radii.', entries(model.rounded, 'rounded')),
    node('Spacing', 'spacing', 'The 4px grid steps (Step4 and up) and layout metrics.',
      entries(model.spacing, 'spacing', (name) => (/^\d/.test(name) ? `Step${pascal(name)}` : pascal(name)))),
    node('Elevation', 'elevation', 'The modal scrim and the one motion.', [
      constant('Scrim', model.elevation.scrim, 'elevation.scrim'),
      ...Object.entries(model.elevation.motion).map(([name, value]) =>
        constant(`Motion${pascal(kebab(name))}`, value, 'elevation.motion')),
    ]),
  ]);
}

export function renderCs(model) {
  const lines = [];
  const indent = (depth) => '    '.repeat(depth);
  const escape = (value) => value.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
  const write = (member, depth) => {
    if (!member.members) {
      lines.push(`${indent(depth)}internal const string ${member.name} = "${escape(member.value)}";`);
      return;
    }
    if (lines.length > 0 && !lines[lines.length - 1].endsWith('{')) lines.push('');
    if (member.summary) lines.push(`${indent(depth)}/// <summary>${member.summary}</summary>`);
    lines.push(`${indent(depth)}internal static class ${member.name}`, `${indent(depth)}{`);
    for (const child of member.members) write(child, depth + 1);
    lines.push(`${indent(depth)}}`);
  };
  for (const member of csPlan(model).members) write(member, 1);

  return (
    '// <auto-generated/>\n' +
    `// ${GENERATED_NOTE.replace(/\n/g, '\n// ')}\n\n` +
    'namespace Gatekeep.Modules.Tenancy.Core.Theme;\n\n' +
    "/// <summary>The default theme's design tokens, from the DESIGN.md frontmatter (AD-22).</summary>\n" +
    'internal static class DesignTokens\n{\n' +
    `${lines.join('\n')}\n}\n`
  );
}

/** Renders every output from DESIGN.md text: a map of repository-relative path to content. */
export function renderAll(markdown) {
  const model = parseDesign(markdown);
  return {
    [OUTPUT_PATHS.css]: renderCss(model),
    [OUTPUT_PATHS.ts]: renderTs(model),
    [OUTPUT_PATHS.cs]: renderCs(model),
  };
}

